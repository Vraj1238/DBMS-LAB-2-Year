SELECT ENAME
FROM EMP E
WHERE SAL = (
    SELECT MAX(SAL)
    FROM EMP
    WHERE DEPTNO = E.DEPTNO
);

SELECT *
FROM EMP
WHERE SAL = (
    (
        SELECT MAX(SAL)
        FROM EMP
    )
    +
    (
        SELECT MIN(SAL)
        FROM EMP
    )
) / 2;

SELECT *
FROM EMP
WHERE HIREDATE IN (
    SELECT HIREDATE
    FROM EMP
    GROUP BY HIREDATE
    HAVING COUNT(*) > 1
);

SELECT *
FROM EMP E
WHERE HIREDATE < (
    SELECT HIREDATE
    FROM EMP
    WHERE EMPNO = E.MGR
);