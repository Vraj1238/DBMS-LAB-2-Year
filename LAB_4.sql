CREATE TABLE CLIENT_MASTER_1 (
    CLIENTNO VARCHAR(6),
    NAME VARCHAR(20) NOT NULL,
    ADDRESS1 VARCHAR(30),
    ADDRESS2 VARCHAR(30),
    CITY VARCHAR(15),
    PINCODE INT,
    STATE VARCHAR(15),
    BALDUE DECIMAL(10,2),
    
    CONSTRAINT PK_CLIENT_MASTER
    PRIMARY KEY (CLIENTNO),

    CONSTRAINT CHK_CLIENTNO
    CHECK (CLIENTNO LIKE 'C%')
);

CREATE TABLE SALESMAN_MASTER_1 (
    SALESMANNO VARCHAR(6),
    SALESMANNAME VARCHAR(20) NOT NULL,
    ADDRESS1 VARCHAR(30) NOT NULL,
    ADDRESS2 VARCHAR(30),
    CITY VARCHAR(20),
    PINCODE INT,
    STATE VARCHAR(20),
    SALAMT REAL NOT NULL,
    TGTTOGET DECIMAL(6,2) NOT NULL,
    YTDSALES DOUBLE NOT NULL,
    REMARKS VARCHAR(60),

    CLIENTNO VARCHAR(6),

    CONSTRAINT PK_SALESMAN_MASTER
    PRIMARY KEY (SALESMANNO),

    CONSTRAINT CHK_SALESMANNO
    CHECK (SALESMANNO LIKE 'S%'),

    CONSTRAINT CHK_SALAMT
    CHECK (SALAMT <> 0),	/*not equal to*/

    CONSTRAINT CHK_TGTTOGET
    CHECK (TGTTOGET <> 0),

    CONSTRAINT FK_SALESMAN_CLIENT
    FOREIGN KEY (CLIENTNO)
    REFERENCES CLIENT_MASTER_1(CLIENTNO)
);

CREATE TABLE PRODUCT_MASTER_1 (
    PRODUCTNO VARCHAR(6),
    DESCRIPTION VARCHAR(15) NOT NULL,
    PROFITPERCENT DECIMAL(4,2) NOT NULL,
    UNIT_MEASURE VARCHAR(10) NOT NULL,
    QTYONHAND INT NOT NULL,
    REORDERLVL INT NOT NULL,
    SELLPRICE DECIMAL(8,2) NOT NULL,
    COSTPRICE DECIMAL(8,2) NOT NULL,
    
    SALESMANNO VARCHAR(6),
    
    CONSTRAINT PK_PRODUCT_MASTER
    PRIMARY KEY (PRODUCTNO),

    CONSTRAINT CHK_PRODUCTNO
    CHECK (PRODUCTNO LIKE 'P%'),

    CONSTRAINT FK_PRODUCT_SALESMAN
    FOREIGN KEY (SALESMANNO)
    REFERENCES SALESMAN_MASTER_1(SALESMANNO)
);

